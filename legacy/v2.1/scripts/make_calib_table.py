#!/usr/bin/env python3
"""Task calibration table: how much each task can possibly reward, and whether that
amount is resolvable at all.

All three columns must be self-explanatory:
  R*(empty)  regret with no experiment at all, i.e. the denominator of c (eq:capture)
  sigma_u/sqrt(B)  what survives after a whole budget averages down unit-level noise
  ratio      only above 1 can an experiment make the difference visible
"""
from __future__ import annotations
import sys, json, pathlib
import numpy as np
ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from slowlab import SlowLabEnv, TASKS

ORDER = ("Sanity", "Optimise", "Screen", "Transfer")
N_INST = 20


def main(out="paper/sections/_calib_table.tex"):
    """Three columns: the ceiling, the leaderboard's own error bar, and their ratio.

    This used to report sigma_u/sqrt(B) as the "noise floor", but sigma_u derived
    from the variance components overstates it by nearly a factor of two (the
    chamber term is one draw shared by the whole chamber and does not average down
    with the number of units), and both sigma_u and B then need separate
    definitions. Use instead the standard error the leaderboard already reports: if
    the prize is smaller than one error bar, no ranking can be built on top of it.
    """
    A = json.loads((ROOT / "results" / "achievable.json").read_text())
    S = json.loads((ROOT / "results" / "summary.json").read_text())
    KEY = {"Sanity": "T1", "Screen": "T2", "Optimise": "T3", "Transfer": "T4"}
    REF = ("random_spread", "classical_doe", "gp_ucb_rep1")
    rows = []
    for cfg in ORDER:
        ceil = A[cfg]["prior"]
        se = float(np.mean([S[KEY[cfg]][a]["regret_se"] for a in REF]))
        sd = se * np.sqrt(N_INST)            # between-instance standard deviation
        need = (2 * sd / ceil) ** 2          # instances needed for the ceiling to equal 2 SEs
        rows.append((cfg, ceil, se, need))

    L = [r"% AUTO-GENERATED by scripts/make_calib_table.py",
         r"\begin{table}[t]", r"\centering\small",
         r"\begin{tabular}{@{}lccc@{}}", r"\toprule",
         r"\textbf{Task} & ceiling $\mathcal{R}^\star(\emptyset)$ &"
         r" s.e.\ of the score & instances to resolve it \\",
         r"\midrule"]
    for cfg, ceil, se, need in rows:
        cell = (r"\textbf{%s}" % f"{need:,.0f}" if need > N_INST else f"{need:,.0f}")
        L.append(f"\\textsc{{{cfg}}} & {ceil:.4f} & {se:.4f} & {cell} \\\\")
    L += [r"\bottomrule", r"\end{tabular}",
          (r"\caption{What each task can reward. The ceiling is \eqref{eq:eig} for a "
           r"design that runs nothing: the most any experiment here could remove, and the "
           r"denominator of \eqref{eq:capture}. The standard error is the one the "
           r"leaderboard already carries, averaged over the three reference strategies. The "
           r"last column is how many instances it would take for two agents separated by the "
           r"whole ceiling to differ by two standard errors. We run " + str(N_INST) +
           r", which suffices on the first two tasks and not on the other two, where "
           r"tailoring a recommendation to the instance is worth too little to be measured "
           r"at any budget we could run.}"),
          r"\label{tab:calib}", r"\end{table}"]
    (ROOT / out).write_text("\n".join(L) + "\n")
    print("wrote", out)
    for cfg, ceil, se, need in rows:
        print(f"  {cfg:9} ceiling={ceil:.4f}  se={se:.4f}  need={need:,.0f}")


if __name__ == "__main__":
    main()
