#!/usr/bin/env python3
"""Leaderboard to LaTeX.

The rows of the main table are the LLM agents under test; scripted strategies are
reference lines in a separate block, marked as not being under test. Adding a
model means adding one summary_*.json under results/llm/, with no code change.

The literature prior is not read in the same column as the reference block: it
runs no experiment at all, so its R_cum is trivially zero and it has no design to
compute EIG over. It is a *normalising baseline*, there to answer whether a model
is experimenting or reciting what it already knew.
"""
from __future__ import annotations
import json, glob, pathlib, re, sys
ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

REF_NAME = {"random_spread": "Random (space-filling)",
            "classical_doe": "Planned design (Plackett--Burman + RSM)",
            "gp_ucb_rep1": "Bayesian optimisation (GP-UCB)"}
MAIN_REF = "gp_ucb_rep1"                    # the single strong reference in the main table
APPENDIX_REFS = ["random_spread", "classical_doe"]
CFG = [("T1", "Sanity"), ("T2", "Screen"), ("T3", "Optimise"), ("T4", "Transfer")]
_OLD = {"sanity-1f": "Sanity", "screen-8f": "Screen",
        "core-2f": "Optimise", "shift-4f": "Transfer"}

BOARD = r"""%% AUTO-GENERATED by scripts/make_tables.py — do not edit by hand.
\begin{table}[t]
\centering\footnotesize
\setlength{\tabcolsep}{2pt}
\begin{tabular}{@{}llccccc@{}}
\toprule
& & \multicolumn{3}{c}{\textbf{Realised regret} \eqref{eq:regret}} &
\multicolumn{2}{c}{\textbf{Efficiency} \eqref{eq:capture},\,\eqref{eq:use}} \\
\cmidrule(lr){3-5}\cmidrule(l){6-7}
\textbf{Task} & \textbf{Agent} & 0-shot & $\bar{\mathcal{R}}(R)\downarrow$ &
$\mathcal{R}_{\mathrm{cum}}\downarrow$ & design $c\uparrow$ & decision $\eta\uparrow$ \\
\midrule
%(rows)s
\bottomrule
\end{tabular}
\caption{Leaderboard: %(n)d instances per task. Adding a model adds a row; the reference row
is Bayesian optimisation. \emph{0-shot} is the same model recommending with no data.
$c$ and $\eta$ are the design and decision efficiencies of \eqref{eq:capture} and
\eqref{eq:use}. A bracketed digit is the standard error in the last places shown, so
$0.0365(75)$ means $0.0365 \pm 0.0075$.}
\label{tab:board}
\end{table}
"""

REFS = r"""%% AUTO-GENERATED by scripts/make_tables.py — do not edit by hand.
\begin{table}[t]
\centering\small
\begin{tabular}{@{}llccc@{}}
\toprule
& & \multicolumn{2}{c}{\textbf{Realised regret}} & \textbf{Information} \\
\cmidrule(lr){3-4}
\textbf{Task} & \textbf{Reference} & $\mathcal{R}(R)$ $\downarrow$ &
$\mathcal{R}_{\mathrm{cum}}$ $\downarrow$ & $\mathcal{I}$ (nats) $\downarrow$ \\
\midrule
%(rows)s
\bottomrule
\end{tabular}
\caption{The full reference set, reported once. These calibrate the tasks rather than compete
on them; only Bayesian optimisation appears in Table~\ref{tab:board}. The two that run no
experiment forgo no profit and submit no designs, so only $\bar{\mathcal{R}}(R)$ is defined
for them.}
\label{tab:refs}
\end{table}
"""


def _fmt(v, se=None, bold=False):
    """Compact uncertainty notation: 0.0365(75) means 0.0365 +/- 0.0075.

    A seven-column table using "0.0365 \\pm 0.0075" overflows the page width,
    while the bracket notation is standard in physics and needs explaining once in
    the table note.
    """
    s = f"{v:.4f}" if abs(v) < 1 else f"{v:.1f}"
    if se is not None:
        digits = int(round(se * 1e4)) if abs(v) < 1 else int(round(se * 10))
        s += f"({digits})"
    return rf"\textbf{{{s}}}" if bold else s


# API slug -> display name for the paper. LaTeX text mode chokes on underscores,
# and a slug should not appear in the body text anyway.
import slowlab
LLM_DIR = f"llm_env{slowlab.ENV_VERSION}"

PRETTY_MODEL = {
    "z-ai_glm-5.3-flash":         "GLM-5.3-flash",
    "deepseek_deepseek-v4-flash": "DeepSeek-V4-flash",
    "xiaomi_mimo-v2.5":           "MiMo-v2.5",
    "openai_gpt-5.6-luna":        "GPT-5.6-luna",
    "qwen_qwen3.8-27b":           "Qwen3.8-27B",
}


def _model_name(slug):
    """An unregistered model must still be safe: escape the underscores rather than break the build."""
    return PRETTY_MODEL.get(slug, slug.replace("_", r"\_"))


def main(out="paper/sections/_results_table.tex"):
    s = json.loads((ROOT / "results" / "summary.json").read_text())
    ep = ROOT / "results" / "eig.json"
    eig = json.loads(ep.read_text()) if ep.exists() else {}
    ap_ = ROOT / "results" / "achievable.json"             # R*(D), see eq:eig
    ach = json.loads(ap_.read_text()) if ap_.exists() else {}

    def _capture(label, key):
        """Design capture = (R*(none) - R*(D)) / R*(none).

        Absolute R*(D) is bounded above by R*(none), and R*(none) is itself only
        0.0004-0.0065; printed next to regrets of 0.03-0.08 neither column shows
        any difference (on Screen three models give R* of 0.0005/0.0006/0.0006).
        Divided by the task's own anchor the same numbers become 39%/22%/33% and
        the difference is visible. The additive identity stays in eq:eig-est and
        the body text.
        """
        d = ach.get(label, {})
        a = d.get("agents", {}).get(key)
        p0 = d.get("prior")
        if a is None or not p0:
            return r"\pending{--}"
        return f"{100 * (p0 - a['R_star']) / p0:.0f}\\%"

    def _use(label, key, realised):
        """What percentage of its own design ceiling the agent reached: R*(D)/R(R).

        Same direction as c(D) -- larger is better, both in [0,1] -- because one
        column rising while another falls is awkward to read in a single table.
        With perfect inference R(R) = R*(D) and this is 100%. The additive form is
        in eq:eig-est.
        """
        a = ach.get(label, {}).get("agents", {}).get(key)
        if a is None or not realised:
            return r"\pending{--}"
        return f"{100 * a['R_star'] / realised:.0f}\\%"
    # Models planned but not yet run. Delete an entry once it has run and that row
    # turns from \\pending{--} into real numbers by itself.
    planned: list[str] = []
    llms = {}
    for f in sorted(glob.glob(str(ROOT / "results" / LLM_DIR / "summary_*.json"))):
        name = re.sub(r"^summary_|\.json$", "", pathlib.Path(f).name)
        name = name.split("@")[0]                 # task subsets run in parallel, merged back by model name
        if name in {"fake", "scripted"} or "+tools" in name:          # the CI fake model stays off the leaderboard
            continue
        d = json.loads(pathlib.Path(f).read_text())
        llms.setdefault(name, {}).update({_OLD.get(k, k): v for k, v in d.items()})
    for m in planned:                     # planned but not yet run: an explicit placeholder
        llms.setdefault(m, {})
    board, refs = [], []
    def _eig(label, a):
        return (f"{100*eig[label]['agents'][a]['eig_frac']:.0f}\\%"
                if label in eig and a in eig[label]["agents"] else r"\pending{--}")

    for key, label in CFG:
        first = True
        for name, d in llms.items():                      # ── leaderboard: agents under test ──
            e = d.get(label)
            if e is None:                                 # planned, not yet run
                board.append(" & ".join([
                    rf"\textsc{{{label}}}" if first else "", rf"\textbf{{{_model_name(name)}}}",
                    r"\pending{--}", r"\pending{--}", r"\pending{--}",
                    r"\pending{--}", r"\pending{--}"]) + r" \\")
                first = False
                continue
            board.append(" & ".join([
                rf"\textsc{{{label}}}" if first else "", rf"\textbf{{{_model_name(name)}}}",
                _fmt(e["regret_zero_shot"]) if e.get("regret_zero_shot") is not None
                else r"\pending{--}",
                _fmt(e["regret"], e.get("regret_se")),
                _fmt(e["cumulative_regret"]) if "cumulative_regret" in e
                else r"\pending{--}",
                _capture(label, name),
                _use(label, name, e.get("regret"))]) + r" \\")
            first = False
        d = s[key][MAIN_REF]                              # ── the single strong reference ──
        board.append(r"\cmidrule(l){2-7}")
        board.append(" & ".join(["", r"\emph{Bayesian optimisation}", "---",
                                 _fmt(d["regret_mean"], d["regret_se"]),
                                 _fmt(d["cumulative_regret"], d["cumulative_regret_se"]),
                                 _capture(label, "ref:" + MAIN_REF),
                                 _use(label, "ref:" + MAIN_REF, d["regret_mean"])]) + r" \\")
        if key != CFG[-1][0]:
            board.append(r"\addlinespace")

        first = True                                      # ── appendix: the full reference set ──
        for a in APPENDIX_REFS + [MAIN_REF]:
            d = s[key][a]
            refs.append(" & ".join([
                rf"\textsc{{{label}}}" if first else "", REF_NAME[a],
                _fmt(d["regret_mean"], d["regret_se"]),
                _fmt(d["cumulative_regret"], d["cumulative_regret_se"]),
                _eig(label, a)]) + r" \\")
            first = False
        from slowlab import TASKS
        from slowlab.fixed_reference import best_fixed
        _, bfr = best_fixed(TASKS[label])
        refs.append(" & ".join(["", "Best fixed recommendation (oracle)",
                                _fmt(bfr), "---", "---"]) + r" \\")
        if key != CFG[-1][0]:
            refs.append(r"\addlinespace")
    n = s["T3"][MAIN_REF]["n_seeds"]
    p = ROOT / out
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(BOARD % {"rows": "\n".join(board), "n": n})
    (p.parent / "_reference_table.tex").write_text(REFS % {"rows": "\n".join(refs)})
    print("wrote", out, "and _reference_table.tex",
          f"({len(llms)} model(s): {', '.join(llms) or 'none'})")


if __name__ == "__main__":
    main()
