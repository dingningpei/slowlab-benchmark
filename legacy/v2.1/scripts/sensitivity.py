#!/usr/bin/env python3
"""Sensitivity analysis: move the parameters that have no literature source up and down
and see whether the conclusions move.

This answers whether the numbers were tuned to support the conclusions. Designs and
recommendations are already on record, so the noise sensitivity can be computed
*without re-running the LLM*: tau enters only the likelihood Sigma(D), not anything
the agent sees.

About 170s per sandbox call, so results are written per task; run repeatedly until
ALL DONE.
"""
from __future__ import annotations
import sys, json, glob, re, pathlib, argparse
import numpy as np
ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "scripts"))
from slowlab import SlowLabEnv, TASKS
from slowlab.achievable import achievable_regret, candidate_set, response_table
from slowlab.registry import make_agent
from eig_of_llm import designs_from, atoms_for
from run_eig import designs_of

CFGS = ("Sanity", "Optimise", "Screen", "Transfer")
MODELS = {"z-ai_glm-5.3-flash": "GLM", "deepseek_deepseek-v4-flash": "DSv4",
          "xiaomi_mimo-v2.5": "MiMo"}
MULT = (0.5, 1.0, 2.0)


def realised(tag, task):
    r = []
    for f in glob.glob(str(ROOT / "results" / "llm" / f"episodes_{tag}@{task}.json")):
        r += json.loads(pathlib.Path(f).read_text())
    return float(np.mean([x["regret"] for x in r]))


def main(M=60, n_outer=60, n_seed=4, out="results/sensitivity.json"):
    fp = ROOT / out
    res = json.loads(fp.read_text()) if fp.exists() else {}
    S = json.loads((ROOT / "results" / "summary.json").read_text())
    KEY = {"Sanity": "T1", "Screen": "T2", "Optimise": "T3", "Transfer": "T4"}
    for cfg in CFGS:
        if cfg in res:
            continue
        t = TASKS[cfg]
        env0 = SlowLabEnv(t, seed=0); sd = env0.truth.response_sd
        a = atoms_for(cfg, M, 12)
        cand = candidate_set(a, rng=np.random.default_rng(0))
        kw = dict(F=response_table(a, cand), cand=cand, n_outer=n_outer)
        d = len(t.factors)
        slot = {}
        for mult in MULT:
            taus = (t.tau_chamber * sd * mult, t.tau_loop * sd * mult,
                    t.tau_batch * sd * mult)
            prior = achievable_regret(a, np.zeros((0, d)), np.zeros(0, int),
                                      *taus, **kw)
            row = {"prior": prior, "c": {}, "eta": {}}
            for slug, name in MODELS.items():
                vals = []
                for f in sorted(glob.glob(str(
                        ROOT / "results" / "llm" /
                        f"transcript_{slug}@{cfg}_{cfg}_s*.json")))[:n_seed]:
                    s = int(re.search(r"_s(\d+)", f).group(1))
                    for p_, b_ in designs_from(f, SlowLabEnv(t, seed=s)):
                        vals.append(achievable_regret(
                            a, p_, b_, *taus,
                            rng=np.random.default_rng(7), **kw))
                rs = float(np.mean(vals))
                row["c"][name] = 100 * (prior - rs) / prior
                row["eta"][name] = 100 * rs / realised(slug, cfg)
            vals = []
            for s in range(min(n_seed, 4)):
                e = SlowLabEnv(t, seed=s); ag = make_agent("gp_ucb_rep1")
                e.submit_recommendation(ag.run(e), "x")
                for p_, b_ in designs_of(e):
                    vals.append(achievable_regret(a, p_, b_, *taus,
                                                  rng=np.random.default_rng(7), **kw))
            rs = float(np.mean(vals))
            row["c"]["BO"] = 100 * (prior - rs) / prior
            row["eta"]["BO"] = 100 * rs / S[KEY[cfg]]["gp_ucb_rep1"]["regret_mean"]
            slot[str(mult)] = row
        res[cfg] = slot
        fp.write_text(json.dumps(res, indent=1))
        print(f"{cfg} done", flush=True)
        return
    print("ALL DONE")
    for cfg in CFGS:
        print(f"\n{cfg}")
        for m in MULT:
            r = res[cfg][str(m)]
            c = "/".join(f"{r['c'][k]:.0f}" for k in ("GLM", "DSv4", "MiMo", "BO"))
            e = "/".join(f"{r['eta'][k]:.0f}" for k in ("GLM", "DSv4", "MiMo", "BO"))
            print(f"  noise x{m:<4} R*(0)={r['prior']:.5f}  c={c}  eta={e}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--M", type=int, default=80)
    main(M=ap.parse_args().M)


def table(out="paper/sections/_sens_table.tex"):
    """Write the sensitivity results out as an appendix table."""
    res = json.loads((ROOT / "results" / "sensitivity.json").read_text())
    L = [r"% AUTO-GENERATED by scripts/sensitivity.py",
         r"\begin{table}[t]", r"\centering\small",
         r"\setlength{\tabcolsep}{4pt}",
         r"\begin{tabular}{@{}llcccc@{}}", r"\toprule",
         r"\textbf{Task} & \textbf{Block noise} & \multicolumn{2}{c}{GLM-5.3-flash}"
         r" & \multicolumn{2}{c}{Bayesian opt.} \\",
         r"\cmidrule(lr){3-4}\cmidrule(l){5-6}",
         r" & & $c$ & $\eta$ & $c$ & $\eta$ \\", r"\midrule"]
    for cfg in CFGS:
        first = True
        for m in MULT:
            r = res[cfg][str(m)]
            lab = r"$\times%s$" % m + (r" \emph{(as run)}" if m == 1.0 else "")
            name = r"\textsc{%s}" % cfg if first else ""
            cells = " & ".join("%.0f\\%%" % r[k][w]
                               for k, w in (("c", "GLM"), ("eta", "GLM"),
                                            ("c", "BO"), ("eta", "BO")))
            L.append(name + " & " + lab + " & " + cells + r" \\")
            first = False
        if cfg != CFGS[-1]:
            L.append(r"\addlinespace")
    L += [r"\bottomrule", r"\end{tabular}",
          r"\caption{Sensitivity of the two efficiencies to the block-noise scale, which is "
          r"the parameter group with no literature value. Halving and doubling "
          r"$\tau_{\mathrm{chamber}}, \tau_{\mathrm{loop}}, \tau_{\mathrm{batch}}$ moves both "
          r"levels but not the comparison: the model's design efficiency stays within reach "
          r"of the reference's at every setting, and its decision efficiency stays a fraction "
          r"of it, with the gap widening as noise rises. Recomputed from the recorded designs "
          r"and recommendations, so no agent was re-run; at reduced settings ($M = 60$, four "
          r"sites) so levels differ slightly from Table~\ref{tab:board}.}",
          r"\label{tab:sens}", r"\end{table}"]
    (ROOT / out).write_text("\n".join(L) + "\n")
    print("wrote", out)
