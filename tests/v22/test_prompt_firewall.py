import hashlib
from pathlib import Path

import pytest

from slowlab.v22.prompt_firewall import (
    audit_outbound_messages,
    blinded_completer,
    load_blinding_policy,
)


ROOT = Path(__file__).resolve().parents[2]
POLICY_PATH = ROOT / "configs" / "v22" / "simulation_blinding_v2_2.json"


def test_current_public_prompt_shape_passes_blinding_firewall():
    policy = load_blinding_policy(POLICY_PATH)
    messages = [
        {"role": "system", "content": "You are an agronomist running experiments in a real greenhouse."},
        {"role": "user", "content": (
            "BUDGET: 3 rounds. day_temp: 18 to 30 degC. "
            "VISIBLE OBSERVATIONS SO FAR: none. "
            "Return randomization_seed with the proposed design."
        )},
    ]
    assert audit_outbound_messages(messages, policy)["status"] == "pass"


@pytest.mark.parametrize("leak", [
    "SlowLab site seed 123",
    "The GreenLight simulator uses these latent parameters",
    "Oracle optimum is 24.1 C",
    "Source: AGC 2024 doi:10.1234/example",
    "/Users/example/project/configs/private.json",
    "This is a synthetic trajectory generated by TOMGRO",
])
def test_known_identity_and_hidden_state_leaks_are_blocked(leak):
    policy = load_blinding_policy(POLICY_PATH)
    report = audit_outbound_messages([{"role": "user", "content": leak}], policy)
    assert report["status"] == "fail"
    assert report["findings"]


def test_wrapper_blocks_before_provider_is_called():
    called = []
    wrapped = blinded_completer(lambda messages: called.append(messages) or "{}", POLICY_PATH)
    with pytest.raises(RuntimeError, match="simulation-blinding firewall"):
        wrapped([{"role": "user", "content": "site_seed=10; oracle=0.9"}])
    assert called == []


def test_wrapper_preserves_provider_metadata_attributes():
    class Fake:
        call_records = [{"usage": {"cost": 0.1}}]
        def __call__(self, messages):
            return "{}"
    wrapped = blinded_completer(Fake(), POLICY_PATH)
    assert wrapped([{"role": "user", "content": "temperature observation = 21 C"}]) == "{}"
    assert wrapped.call_records[0]["usage"]["cost"] == 0.1


def test_blinding_policy_matches_frozen_hash():
    expected = (ROOT / "configs" / "v22" / "simulation_blinding_v2_2.sha256").read_text().split()[0]
    assert hashlib.sha256(POLICY_PATH.read_bytes()).hexdigest() == expected
