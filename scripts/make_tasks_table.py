#!/usr/bin/env python3
"""Table 2 (the four tasks). It was maintained by hand and had already drifted once,
so it is generated by script.

Two columns need explaining:

R*(empty)  taken from the cross-validated results/achievable_cv_*.json, the same
       estimator and the same atom count as Table 3. Table 2 previously used the
       in-sample M=80 value while Table 3 had moved to cv M=320, so the two tables
       reported the same quantity with different numbers -- exactly the kind of
       inconsistency a script removes.

sigma_tot/sqrt(B)  "how small a whole budget can drive the mean error". This used to
       say only "measured from the simulator", with no executable definition and no
       way to reproduce it. It is pinned here to the analytic variance-component
       expression:

           Var(ȳ) = sd² · ( τ_loop²/B + τ_chamber²/(C·R) + τ_batch²/R )

       -- unit-level noise averages over all B observations; the chamber effect is
       shared within a chamber and averages only over (chambers x rounds); the batch
       effect is shared by a whole round and averages only over rounds. The last two
       do not fall with B, which is precisely where adding units buys no precision.

    python scripts/make_tasks_table.py
"""
from __future__ import annotations
import json, pathlib, sys
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import slowlab
from slowlab import SlowLabEnv, TASKS

CFGS = ("Sanity", "Screen", "Optimise", "Transfer")
WHAT = {"Sanity": ("Close the loop at all", "1 (day temp.)"),
        "Screen": ("Find which factors matter", "6 (management)"),
        "Optimise": ("Find the optimum, respecting the facility", "2 (mixed level)"),
        "Transfer": ("Survive an energy price shock", "4 (resource)")}


def sigma_of(cfg):
    t = TASKS[cfg]
    env = SlowLabEnv(t, seed=0)
    sd = env.truth.response_sd
    units = env.facility.units[:t.units_per_round]
    C = len({u.chamber for u in units})
    B = t.n_rounds * t.units_per_round
    var = sd ** 2 * (t.tau_loop ** 2 / B
                     + t.tau_chamber ** 2 / (C * t.n_rounds)
                     + t.tau_batch ** 2 / t.n_rounds)
    return float(np.sqrt(var)), B, C


def main():
    cvp = ROOT / "results" / f"achievable_cv_env{slowlab.ENV_VERSION}_M320.json"
    cv = json.loads(cvp.read_text())
    rows, meta = [], {}
    for cfg in CFGS:
        t = TASKS[cfg]
        env = SlowLabEnv(t, seed=0)
        nch = len({u.chamber for u in env.facility.units})
        nlo = len(env.facility.units) // nch
        s, B, C = sigma_of(cfg)
        P = cv[cfg]["prior"]
        days = int(t.n_rounds * t.cycle_days)
        what, nf = WHAT[cfg]
        meta[cfg] = {"prior": P, "sigma": s, "ratio": P / s, "B": B, "days": days}
        rows.append(rf"\textsc{{{cfg}}} & {what} & {nf} & ${nch}\times{nlo}$ & "
                    rf"${t.n_rounds} \times {t.units_per_round}$ & {days} & "
                    rf"{P:.4f} & {s:.4f} & {P/s:.1f} \\")

    L = [r"%% Table 2 -- generated by scripts/make_tasks_table.py; do not edit by hand.",
         r"\begin{table}[t]", r"\centering\footnotesize",
         r"\setlength{\tabcolsep}{3pt}",
         r"\begin{tabular}{@{}llccccccc@{}}", r"\toprule",
         r"\textbf{Task} & \textbf{What the agent must do} & \textbf{Factors} &"
         r" \textbf{Facility} & \textbf{$R \times$ units} & \textbf{days} &"
         r" $\mathcal{R}^\star(\varnothing)$ & $\sigma_{\mathrm{tot}}/\sqrt{B}$ &"
         r" ratio \\", r"\midrule", *rows, r"\bottomrule", r"\end{tabular}",
         r"\caption{The four tasks. \emph{Facility} is chambers $\times$ loops and"
         r" \emph{$R\times$units} is rounds times units per round; \emph{mixed level}"
         r" means one chamber-level and one loop-level factor."
         r" \emph{$\mathcal{R}^\star(\varnothing)$} is \eqref{eq:eig} with no data: the"
         r" most any experiment on the task could remove."
         r" \emph{$\sigma_{\mathrm{tot}}/\sqrt{B}$} is the standard error of the mean"
         r" response a full budget of $B$ units achieves (Appendix~\ref{app:tasks})."
         r" \emph{ratio} is the first over the second.}",
         r"\label{tab:tasks}", r"\end{table}"]
    (ROOT / "paper" / "sections" / "_tasks_table.tex").write_text(
        "\n".join(L) + "\n")
    (ROOT / "results" / f"tasks_table_env{slowlab.ENV_VERSION}.json").write_text(
        json.dumps(meta, indent=1))
    print(f"{'task':10s}{'R*(∅)':>9}{'σ':>9}{'ratio':>7}{'B':>5}{'days':>6}")
    for cfg in CFGS:
        m = meta[cfg]
        print(f"{cfg:10s}{m['prior']:9.4f}{m['sigma']:9.4f}{m['ratio']:7.1f}"
              f"{m['B']:5d}{m['days']:6d}")
    print("\nwrote sections/_tasks_table.tex")


if __name__ == "__main__":
    main()
