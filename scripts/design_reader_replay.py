#!/usr/bin/env python3
"""Cross fixed design histories with readers and report design/reader interaction."""
from __future__ import annotations

import argparse
import json
import pathlib
import sys
from collections import defaultdict

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from slowlab import SlowLabEnv, TASKS
from slowlab.registry import make_agent
from slowlab.replay import (ComponentGPReader, FixedHistoryLLMReader,
                            OrdinaryGPReader, PrivilegedSiteReader,
                            calibrated_block_reader)


def candidate_set(task, seed=991, n=5000):
    if task.d == 1:
        return np.linspace(0, 1, 1001)[:, None]
    return np.random.default_rng(seed + task.d).random((n, task.d))


def score(env, point):
    if getattr(env.task, "transfer_energy_shock", None) is not None:
        shock = float(env.task.transfer_energy_shock)
        _, best = env.truth.oracle_at(shock)
        return float(best - env.truth.profit_at(point[None, :], shock)[0])
    _, best = env.truth.oracle()
    return float(best - env.truth(point[None, :])[0])


def effects(rows, deployable_readers):
    rows = [row for row in rows if row["reader"] in deployable_readers]
    cells = defaultdict(list)
    for row in rows:
        cells[(row["design"], row["reader"])].append(row["regret"])
    means = {key: float(np.mean(values)) for key, values in cells.items()}
    designs = sorted({key[0] for key in means})
    readers = sorted({key[1] for key in means})
    grand = float(np.mean(list(means.values())))
    design_means = {d: float(np.mean([means[d, r] for r in readers])) for d in designs}
    reader_means = {r: float(np.mean([means[d, r] for d in designs])) for r in readers}
    interactions = {f"{d}|{r}": means[d, r] - design_means[d] - reader_means[r] + grand
                    for d in designs for r in readers}
    return {
        "cell_means": {f"{d}|{r}": means[d, r] for d in designs for r in readers},
        "grand_mean": grand,
        "design_means": design_means,
        "reader_means": reader_means,
        "design_effect_range": max(design_means.values()) - min(design_means.values()),
        "reader_effect_range": max(reader_means.values()) - min(reader_means.values()),
        "interaction_rms": float(np.sqrt(np.mean(np.square(list(interactions.values()))))),
        "interactions": interactions,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--tasks", nargs="+", default=["T1", "T3", "T4"])
    parser.add_argument("--designs", nargs="+", default=[
        "random_spread", "split_plot_doe", "constraint_aware_batch_bo"])
    parser.add_argument("--seeds", type=int, default=8)
    parser.add_argument("--seed-start", type=int, default=4000)
    parser.add_argument("--llm-model", default=None)
    parser.add_argument("--include-llm-design", action="store_true",
                        help="add a design history generated by the same LLM")
    parser.add_argument("--out", default=str(
        ROOT.parent / "slowlab" / "output" / "reviews" /
        "phase3_design_reader_replay.json"))
    args = parser.parse_args()
    config = json.loads((ROOT / "configs" / "block_aware_gp_phase3.json").read_text())
    llm_reader = None
    if args.llm_model:
        from slowlab.providers import openai_compatible
        llm_reader = FixedHistoryLLMReader(openai_compatible(args.llm_model, temperature=0.0))
    if args.include_llm_design and not args.llm_model:
        parser.error("--include-llm-design requires --llm-model")
    designs = list(args.designs) + (["llm_design"] if args.include_llm_design else [])

    rows = []
    for task_name in args.tasks:
        task = TASKS[task_name]
        points = candidate_set(task)
        for seed in range(args.seed_start, args.seed_start + args.seeds):
            for design_name in designs:
                env = SlowLabEnv(task, seed=seed)
                if design_name == "llm_design":
                    from slowlab.llm import LLMAgent
                    LLMAgent(complete=llm_reader.complete, name=args.llm_model).run(env)
                else:
                    make_agent(design_name).run(env)
                readers = [OrdinaryGPReader(), calibrated_block_reader(task_name, config),
                           ComponentGPReader(), PrivilegedSiteReader()]
                if llm_reader is not None:
                    readers.append(llm_reader)
                for reader in readers:
                    point = reader.recommend(env, candidates=points)
                    rows.append({"task": task_name, "seed": seed,
                                 "design": design_name, "reader": reader.name,
                                 "privileged": reader.privileged,
                                 "regret": score(env, point),
                                 "recommendation": point.tolist(),
                                 "history_events": len(env.history())})
    deployable = ["ordinary_gp", "block_aware_gp", "component_gp"]
    if llm_reader is not None:
        deployable.append("llm_reader")
    report = {
        "protocol_version": "phase3-design-reader-replay-0.1",
        "tasks": args.tasks, "designs": designs,
        "heldout_seeds": list(range(args.seed_start, args.seed_start + args.seeds)),
        "fixed_history": True,
        "deployable_readers": deployable,
        "privileged_readers": ["site_oracle"],
        "effects_by_task": {
            task: effects([row for row in rows if row["task"] == task], deployable)
            for task in args.tasks},
        "overall_effects": effects(rows, deployable),
        "rows": rows,
        "llm_records": [] if llm_reader is None else llm_reader.records,
    }
    out = pathlib.Path(args.out); out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2))
    print(json.dumps({"effects_by_task": report["effects_by_task"],
                      "overall": report["overall_effects"],
                      "out": str(out)}, indent=2))


if __name__ == "__main__":
    main()
