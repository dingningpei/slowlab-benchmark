#!/usr/bin/env python3
"""Rebuild the two tables of section 4.6: design-shape diagnostics and the tool ablation.

Design shape is aggregated by (model x task), because the claim in section 4.6 is
that the habit is shared by all three models rather than a quirk of one -- a
sentence that only stands up when the three rows are placed side by side.
"""
from __future__ import annotations
import sys, json, glob, re, pathlib
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))
from slowlab import SlowLabEnv, TASKS
from slowlab.llm import _extract_json
from eig_of_llm import designs_from

# Display names: LaTeX will not take underscores, and the paper should use the
# vendor's spelling rather than the API slug
PRETTY = {
    "z-ai_glm-5.3-flash":        "GLM-5.3-flash",
    "deepseek_deepseek-v4-flash": "DeepSeek-V4-flash",
    "xiaomi_mimo-v2.5":          "MiMo-v2.5",
}
TASKS_ORDER = ("Sanity", "Screen", "Optimise", "Transfer")


def shape(tag, T):
    """Design-shape statistics for one (model, task) cell."""
    t = TASKS[T]
    n_tr, rank_ok, rep, purecol = [], [], [], []
    for f in sorted(glob.glob(str(ROOT / "results" / "llm" /
                                  f"transcript_{tag}@{T}_{T}_s*.json"))):
        env = SlowLabEnv(t, seed=int(re.search(r"_s(\d+)", f).group(1)))
        for pts, _ in designs_from(f, env):
            u = np.unique(pts, axis=0)
            n_tr.append(len(u))
            rep.append(len(pts) / max(len(u), 1))
            purecol.append(len(pts) - len(u))          # pure-error degrees of freedom
            varying = [j for j in range(pts.shape[1]) if np.ptp(u[:, j]) > 1e-9]
            if varying:
                X = np.c_[np.ones(len(u)), u[:, varying]]
                rank_ok.append(np.linalg.matrix_rank(X) == X.shape[1])
    if not n_tr:
        return None
    return dict(n=len(n_tr), n_tr=float(np.mean(n_tr)),
                two=100 * float(np.mean([k == 2 for k in n_tr])),
                rep=float(np.mean(rep)), pure=float(np.mean(purecol)),
                est=100 * float(np.mean(rank_ok)) if rank_ok else float("nan"))


def diag_table():
    rows = []
    for tag, name in PRETTY.items():
        for T in TASKS_ORDER:
            s = shape(tag, T)
            if s:
                rows.append((name, T, s))
    L = [r"% AUTO-GENERATED by scripts/make_diag_table.py",
         r"\begin{table}[t]", r"\centering\small",
         r"\setlength{\tabcolsep}{5pt}",
         r"\begin{tabular}{@{}llcccc@{}}", r"\toprule",
         r"\textbf{Model} & \textbf{Task} & \textbf{designs} & \textbf{2-treat.}"
         r" & \textbf{repl.} & \textbf{effects} \\",
         r" & & & \textbf{designs} & \textbf{per treat.} & \textbf{estimable} \\",
         r"\midrule"]
    last = None
    for name, T, s in rows:
        head = name if name != last else ""
        if last is not None and name != last:
            L.append(r"\addlinespace")
        last = name
        L.append(f"{head} & \\textsc{{{T}}} & {s['n']} & {s['two']:.0f}\\% & "
                 f"{s['rep']:.1f} & {s['est']:.0f}\\% \\\\")
    L += [r"\bottomrule", r"\end{tabular}",
          r"\caption{Design shape, over every design the three models submitted "
          r"($n$ per cell). ``2-treat.\ designs'' is the fraction using exactly two "
          r"distinct treatments; ``effects estimable'' is the fraction whose design "
          r"matrix has full rank over the factors that design actually varies. The "
          r"two-treatment habit is common to all three models and is harmless on "
          r"\textsc{Sanity}, where one factor is varied, but leaves almost every "
          r"\textsc{Screen} design rank-deficient against six.}",
          r"\label{tab:diag}", r"\end{table}"]
    return "\n".join(L) + "\n"


def tools_table():
    """Three models x four tasks, with and without the tool, paired on the seed.

    The pairing is the only source of power in this table (same site, same truth,
    same budget), so it is done episode by episode. The regression at the end answers
    whether the tool shifts or compresses: only a slope significantly below 1 is the
    latter.
    """
    import numpy as np
    from scipy import stats

    def ep(tag):
        d = {}
        for f in glob.glob(str(ROOT / "results" / "llm" / f"episodes_{tag}@*.json")):
            for r in json.loads(pathlib.Path(f).read_text()):
                d[(r["task"], r["seed"])] = r["regret"]
        return d

    L = [r"% AUTO-GENERATED by scripts/make_diag_table.py",
         r"\begin{table}[t]", r"\centering\small",
         r"\setlength{\tabcolsep}{5pt}",
         r"\begin{tabular}{@{}llccccc@{}}", r"\toprule",
         r"\textbf{Model} & \textbf{Task} & \multicolumn{2}{c}{$\bar{\mathcal{R}}(R)$}"
         r" & \textbf{paired $\Delta$} & \textbf{$t$} & \textbf{sites} \\",
         r" & & no tools & with tools & & & improved \\",
         r"\midrule"]
    A_all, B_all = [], []
    for slug, name in PRETTY.items():
        A, B = ep(slug), ep(slug + "+tools")
        if not B:
            continue
        if A_all:
            L.append(r"\addlinespace")
        first = True
        for T in TASKS_ORDER:
            ks = sorted(k for k in A if k[0] == T and k in B)
            if not ks:
                continue
            a = np.array([A[k] for k in ks]); b = np.array([B[k] for k in ks])
            d = a - b; se = d.std(ddof=1) / len(d) ** .5
            star = r"$^{*}$" if abs(d.mean() / se) > 2 else ""
            A_all.append(a.mean()); B_all.append(b.mean())
            L.append(f"{name if first else ''} & \\textsc{{{T}}} & {a.mean():.4f} & "
                     f"{b.mean():.4f} & {d.mean():+.4f}{star} & {d.mean()/se:+.2f} & "
                     f"{int((b<a).sum())}/{len(ks)} \\\\")
            first = False
    r = stats.linregress(np.array(A_all), np.array(B_all))
    t = (r.slope - 1) / r.stderr
    L += [r"\bottomrule", r"\end{tabular}",
          r"\caption{Realised regret with and without a screening-design generator and a "
          r"posterior-maximisation routine, on the same 20 sites per task. $\\Delta>0$ "
          r"favours the tool; $^{*}$ marks paired $|t|>2$.}",
          r"\label{tab:tools}", r"\end{table}"]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    out = ROOT / "paper" / "sections"
    (out / "_diag_table.tex").write_text(diag_table())
    (out / "_tools_table.tex").write_text(tools_table())
    print("wrote _diag_table.tex, _tools_table.tex")
    print(diag_table())
    print(tools_table())
